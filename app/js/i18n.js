const SUPPORTED_LANGS = Object.keys(I18N);

function langSetting() {
  try { return localStorage.getItem('ta_lang') || 'auto'; } catch (e) { return 'auto'; }
}
// 'auto': the first supported language in the browser's preference list (set from the OS by default)
function resolveLang(setting = langSetting()) {
  if (SUPPORTED_LANGS.includes(setting)) return setting;
  const prefs = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || 'en'];
  for (const l of prefs) {
    const base = String(l).toLowerCase().split('-')[0];
    if (SUPPORTED_LANGS.includes(base)) return base;
  }
  return 'en';
}
let LANG = resolveLang();

function localeOf(lang = LANG) {
  return lang === 'ja' ? 'ja-JP' : 'en-GB';
}
function encodingLabel(enc) {
  return enc; // technical names (UTF-8, Shift_JIS, Word (.docx)) are the same in every language
}

function tr(key, params = {}, lang = LANG) {
  const msg = (I18N[lang] && I18N[lang][key]) ?? I18N.en[key];
  if (msg === undefined) { console.warn('Missing message:', key); return key; }
  if (typeof msg === 'function') return msg(params || {}, lang);
  return msg.replace(/\{(\w+)\}/g, (m, k) => (params && params[k] !== undefined && params[k] !== null) ? String(params[k]) : m);
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = tr(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = tr(el.dataset.i18nHtml); }); // dictionary text only
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = tr(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = tr(el.dataset.i18nTitle); });
}

function setLanguage(setting) {
  try { localStorage.setItem('ta_lang', setting); } catch (e) { /* private mode */ }
  LANG = resolveLang(setting);
  applyI18n();
  // Dropdowns filled from code
  const jt = document.getElementById('journalType'), jd = document.getElementById('jdType');
  if (jt) { const v = jt.value; jt.innerHTML = journalTypeOptions(v); }
  if (jd) { const v = jd.value; jd.innerHTML = journalTypeOptions(v); }
  // An untouched team-discussion outline follows the language too
  for (const id of ['journalText', 'jdText']) {
    const ta = document.getElementById(id);
    if (ta && typeof isUntouchedTemplate === 'function' && isUntouchedTemplate(ta.value)) ta.value = tr('jt.meetingTemplate');
  }
  if (typeof renderAll === 'function') renderAll();
  if (typeof updateJournalDraftIndicators === 'function') updateJournalDraftIndicators();
  if (typeof journalIsOpen === 'function' && journalIsOpen()) renderJournalDrawer();
}
